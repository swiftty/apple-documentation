    func test_TechnologyDetail_AllURLs(argument: Argument<String>) async throws {
        let identifier = argument.value
        let url = try #require(
            URL(string: "https://developer.apple.com/tutorials/data/\(identifier).json"),
            sourceLocation: argument.sourceLocation
        )
        let (data, _) = try await URLSession.shared.data(from: url)

        #expect(throws: Never.self, "Failed to decode: \(identifier)", sourceLocation: argument.sourceLocation) {
            try decodeTechnologyDetail(from: data)
        }
    }

